export function playSabotageAlert() {
  if (isMuted) return;
  try {
    const ctx = getAudioContext();
    if (!ctx) return;
    const now = ctx.currentTime;

    for (let i = 0; i < 2; i++) {
      const osc = ctx.createOscillator();
      const gain = ctx.createGain();
      osc.connect(gain);
      gain.connect(ctx.destination);

      osc.type = 'square';
      osc.frequency.setValueAtTime(880, now + i * 0.15);
      osc.frequency.setValueAtTime(440, now + i * 0.15 + 0.08);

      gain.gain.setValueAtTime(0.15, now + i * 0.15);
      gain.gain.exponentialRampToValueAtTime(0.01, now + i * 0.15 + 0.14);

      osc.start(now + i * 0.15);
      osc.stop(now + i * 0.15 + 0.14);
    }
  } catch {}
}
